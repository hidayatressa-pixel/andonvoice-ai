export type TranslationKey = keyof typeof translations.id;

export function getTranslation(lang: string = "id", key: TranslationKey, params?: Record<string, string | number>): string {
  const safeLang = (lang === "en" || lang === "id") ? lang : "id";
  const dict = translations[safeLang] || translations.id;
  let text = (dict as Record<string, string>)[key] || translations.id[key] || String(key);
  
  if (params) {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
    });
  }
  return text;
}
